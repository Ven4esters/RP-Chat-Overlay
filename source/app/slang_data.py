"""Встроенные сокращения по языкам / built-in abbreviations per language.

Зачем отдельный файл / why a separate file
------------------------------------------
Сокращения живого чата есть у каждого языка, а не только у английского: на
итальянском сервере пишут «cmq» и «xke», на немецком — «hdl» и «kA», на
арабском — «ان شاء الله» и «ههههه». Держать всё это в одном словаре рядом с
кодом разбора значило бы утопить логику в данных, поэтому данные лежат здесь,
а `app.slang` занимается только заменой.

Every language has its own chat abbreviations, not just English: an Italian
server writes "cmq" and "xke", a German one "hdl" and "kA", an Arabic one
"ان شاء الله" and "ههههه". Keeping all of that in one dictionary next to the
parsing code would drown the logic in data, so the data lives here and
`app.slang` only does the replacement.

Как устроена запись / the shape of an entry
-------------------------------------------
    "brb": "I'll be right back"

Ключ — как пишут в чате, значение — полная фраза на том же языке. Разворот
уходит в переводчик ДО перевода, поэтому падеж и время получаются верными:
«brb» → «I'll be right back» → «я скоро вернусь». Именно поэтому здесь полная
фраза, а не готовый русский перевод.

The key is what people type, the value is the full phrase in the same language.
The expansion goes to the translator BEFORE translation, so case and tense come
out right. That is why the value is a full phrase rather than a Russian
translation.

Смайлы не трогаем / smilies are left alone
------------------------------------------
Токены вроде «xD», «x)», «:)», «^^» — это не сокращения, а выражение лица.
В служебных чатах `/b`, `/ab`, `/f` они остаются как есть: замена «xD» на
«haha» посреди смайла ломает и смысл, и вид строки. Поэтому в таблицу они не
входят, а `app.slang` дополнительно пропускает токены с закрывающей скобкой.

Tokens like "xD", "x)", ":)", "^^" are faces rather than abbreviations. In the
service chats `/b`, `/ab`, `/f` they stay as typed: replacing "xD" with "haha"
mid-smiley breaks both the meaning and the look of the line. They are therefore
not in the tables, and `app.slang` additionally skips tokens with a closing
bracket.

У каждого языка своя таблица / one table per language
------------------------------------------------------
Таблица языка отвечает за прямую сторону: сокращение собеседника → полная фраза
на его языке. Русская таблица — обратная сторона: русское сокращение → полная
русская запись, её получает переводчик в направлении «русский → язык».
Короткий русский вариант (``RU_SHORT``) один на все языки: он подставляется уже
после перевода, когда сервис вернул латиницу, и от языка источника не зависит.

A language table serves the forward side: the partner's abbreviation turned into
a full phrase in their language. The Russian table is the reverse side: a Russian
abbreviation turned into the full Russian phrase the translator receives when
translating Russian into the target language. The short Russian variant
(``RU_SHORT``) is shared by every language: it is substituted after translation,
when a service answers in Latin letters, and does not depend on the source.

Арабский — арабской графикой / Arabic in Arabic script
------------------------------------------------------
Арабские сокращения записаны арабскими буквами, как их и пишут в чате, а не
латиницей: «ههههه», а не «hahaha». Латиница в арабском чате встречается, но
это уже английские сокращения, и они берутся из английской таблицы.

Arabic abbreviations are written in Arabic letters as people type them, not in
Latin: "ههههه", not "hahaha". Latin does appear in Arabic chat, but that is
English shorthand and comes from the English table.
"""

