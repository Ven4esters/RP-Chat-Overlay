# Старые файлы data/slang.json не знали языка: всё, что в них лежало, считалось
# английским. Этот ключ — язык по умолчанию для записей без поля lang.
# Old data/slang.json files knew no language: whatever they held counted as
# English. This key is the default language for entries without a lang field.
DEFAULT_LANG: Final[str] = "en"


def table(code: str) -> dict[str, str]:
    """Встроенная таблица языка; неизвестный язык — английская.

    The built-in table of a language; an unknown one falls back to English.

    Английский выбран не наугад: латинские сокращения узнаёт любой игрок, и
    подставлять вместо них пустоту было бы хуже.

    English is not an arbitrary choice: every player recognises the Latin
    abbreviations, and empty tables would be worse.
    """
    return BY_LANG.get((code or "").lower(), ENGLISH)
